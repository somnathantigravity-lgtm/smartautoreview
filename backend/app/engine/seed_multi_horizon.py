IST = timezone(timedelta(hours=5, minutes=30))
DB_PATH = os.path.join(os.path.dirname(__file__), "recommendations.db")

def is_market_open_now() -> bool:
    now_ist = datetime.now(IST)
    if now_ist.weekday() > 4:  # Weekend
        return False
    market_open = now_ist.replace(hour=9, minute=15, second=0, microsecond=0)
    market_close = now_ist.replace(hour=15, minute=30, second=0, microsecond=0)
    return market_open <= now_ist <= market_close

def fmt_ts(epoch_val: float) -> str:
    """Formats epoch float into DD.MM.YYYY HH:MM:SS format in IST."""
    return datetime.fromtimestamp(epoch_val, tz=IST).strftime("%d.%m.%Y %H:%M:%S")

